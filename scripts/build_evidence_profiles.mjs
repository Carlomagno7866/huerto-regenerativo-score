function buildAliases(commonName, scientificName) {
  const stopAliases = new Set([
    "incl",
    "leafy",
    "black",
    "white",
    "green",
    "sweet",
    "italian",
    "japanese",
    "perennial",
    "red",
    "sp",
    "spp",
    "subsp",
    "sativa",
    "sativum"
  ]);
  const raw = [commonName, scientificName.split(" ")[0], scientificName.split(" ")[1] ?? ""]
    .map((value) => value.toLowerCase().replace(/[^a-z ]/g, " ").trim())
    .filter((value) => value.length > 3 && !stopAliases.has(value));
  const parts = raw
    .flatMap((value) => value.split(/\s+|\/|,/))
    .filter((value) => value.length > 3 && !stopAliases.has(value));
  return Array.from(new Set([...raw, ...parts])).slice(0, 8);
}

function mergeCuratedCatalogRows(rows) {
  const byId = new Map();
  for (const row of [...rows, ...CURATED_EXTRA_CROPS]) {
    const key = slugKey(row.scientificName);
    if (!byId.has(key) || CURATED_EXTRA_CROPS.some((crop) => slugKey(crop.scientificName) === key)) {
      byId.set(key, row);
    }
  }
  return Array.from(byId.values());
}

function isCuratedGardenCrop(scientificName) {
  return CURATED_GARDEN_CROPS.has(normalizeCatalogText(scientificName));
}

function normalizeCatalogText(value) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/^[vf]-/, "")
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function slugKey(value) {
  return normalizeCatalogText(value).replace(/[^a-z0-9]+/g, "-");
}

