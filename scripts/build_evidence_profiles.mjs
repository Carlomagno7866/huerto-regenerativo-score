function curatedNutritionFor(scientificName, commonName) {
  const normalized = `${scientificName} ${commonName}`.toLowerCase().replace(/×/g, "x").replace(/[^a-z0-9 ]/g, " ");
  return curatedNutritionProfiles().find((profile) => profile.match.some((item) => normalized.includes(item)));
}

function food(match, description, label, level = "observed") {
  return {
    description,
    level,
    label,
    source:
      "USDA FoodData Central local; criterio de match FAO/INFOODS; contraste nacional Tabla de Composicion Quimica de Alimentos Chilenos",
    match: [match.toLowerCase().replace(/[^a-z0-9 ]/g, " ").trim()]
  };
}

function nonFood(match, label) {
  return {
    foodCrop: false,
    label,
    source: "Revision curada FDC/FAO INFOODS/Tabla chilena; se conserva valor nutricional humano como ausente",
    match: [match.toLowerCase().replace(/[^a-z0-9 ]/g, " ").trim()]
  };
}
